<#
.SYNOPSIS
    Deploy Claude Cowork 3P configuration via Intune platform script.

.DESCRIPTION
    Writes CoWork 3P registry values to HKCU\SOFTWARE\Policies\Claude.
    Claude Desktop reads these at launch as managed MDM policy.

    Standard users can read that key but not write it, so this script fails
    when it runs with a standard user's credentials, and as SYSTEM it writes
    SYSTEM's own HKCU. It works in an elevated session of the user's own
    account. For standard users, deploy the ADMX template instead
    (deployment/mdm/README.md). It uses the legacy AWS profile mode, which needs
    Keyring credential storage, and has not been validated end to end.

    Intune deployment:
      Devices > Scripts and remediations > Platform scripts > Add (Windows 10+)
      Run this script using the logged on credentials: Yes (as SYSTEM it would
        write SYSTEM's own HKCU); it still fails for standard users, see above
      Run script in 64 bit PowerShell Host: Yes

    Omnissa Workspace ONE:
      Devices > Profiles & Resources > Scripts > Add
      Execution context: User

.NOTES
    Generated by: gip cowork generate --format ps1
    Customize the $config hashtable below to match your deployment profile.
    See: https://github.com/aws-samples/sample-governed-generative-ai-inference-solution-on-amazon-bedrock
#>

$ErrorActionPreference = 'Stop'

# ===== CONFIGURATION — EDIT THESE VALUES =====

$config = @{
    # Required: Inference provider (always "bedrock" for this solution)
    inferenceProvider       = "bedrock"

    # Required: AWS region with Bedrock model access
    inferenceBedrockRegion  = "us-east-1"

    # Required: AWS CLI profile name (must match ~/.aws/config stanza with credential_process)
    inferenceBedrockProfile = "gip"

    # Required: Available model aliases (JSON array)
    inferenceModels         = '["opus","sonnet","haiku"]'

    # Feature toggles
    isClaudeCodeForDesktopEnabled       = "true"
    isDesktopExtensionEnabled           = "true"
    isDesktopExtensionDirectoryEnabled  = "true"
    isDesktopExtensionSignatureRequired = "true"
    isLocalDevMcpEnabled                = "true"

    # Optional: OTLP telemetry (uncomment to enable)
    # otlpEndpoint = "http://localhost:4318"
    # otlpProtocol = "http/protobuf"
    # otlpHeaders  = '{"X-Cowork-Token": "your-service-token"}'
}

# ===== END CONFIGURATION =====

$regPath = "HKCU:\SOFTWARE\Policies\Claude"

# Create registry key if it doesn't exist
if (-not (Test-Path $regPath)) {
    New-Item -Path $regPath -Force | Out-Null
}

# Write each configuration value as REG_SZ
foreach ($key in $config.Keys) {
    $value = $config[$key]
    if ($null -ne $value -and $value -ne "") {
        Set-ItemProperty -Path $regPath -Name $key -Value $value -Type String
        Write-Output "  Set $key"
    }
}

Write-Output "`nClaude Cowork 3P policy deployed to $regPath"
Write-Output "Restart Claude Desktop to apply changes."
